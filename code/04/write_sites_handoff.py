#!/usr/bin/env python3
"""Write explicit 05 -> 06 inputs, including the original Adar source-ANN format."""

import argparse
import csv
import json
import shlex
from pathlib import Path


def main():
    ap = argparse.ArgumentParser()
    for name in ("cdspos-dir", "edited-dir", "candidate-root", "alledit-dir", "out"):
        ap.add_argument("--" + name, required=True)
    a = ap.parse_args()
    cds = Path(a.cdspos_dir).resolve()
    edited = Path(a.edited_dir).resolve()
    out = Path(a.out).resolve()
    prefix = ".candidate.rescue_3R_18907675.sourceCDS.keepTargetUTR3"
    paths = {
        "EDIT_ROOT": cds,
        "GLM_CODON_FILE": edited / "dmel-all-CDS-r6.12.fasta.edited.tab.split",
    }
    for group in ("WBG", "AG", "AS", "ISO1"):
        paths["GLM_EDIT_" + group] = cds / (
            group + prefix + ".full_with_longest_projection.tsv"
        )
    required = list(paths.values())[1:] + [
        cds / (g + prefix + ".cdspos_for_alledit.tsv")
        for g in ("ISO1", "sim", "sec", "ere")
    ]
    for path in required:
        if not path.is_file() or not path.stat().st_size:
            raise FileNotFoundError(path)
    # Adar model reads original source ANN + HGVS c., not new_transcript/new_cds_pos.
    # Preserve that original model input contract and current WBG candidate scope.
    source = (
        Path(a.candidate_root)
        / "raw_rows_by_group/WBG.candidate.AtoG.annotations.long.tsv"
    )
    with source.open() as f:
        reader = csv.DictReader(f, delimiter="\t")
        for col in ("lib", "ann", "hgvs_c", "altcount", "refcount"):
            if col not in reader.fieldnames:
                raise ValueError("Missing Adar source column: " + col)
        rows = list(reader)
        fields = list(reader.fieldnames)
    for col in ("sample", "change"):
        if col not in fields:
            fields.append(col)
    adar = out.parent / "06_handoff_Adar"
    adar.mkdir(parents=True, exist_ok=True)
    with (adar / "WBG.candidate.rows.tsv2").open("w") as f:
        writer = csv.DictWriter(
            f, fieldnames=fields, delimiter="\t", lineterminator="\n"
        )
        writer.writeheader()
        for row in rows:
            row["sample"] = row["lib"]
            row["change"] = row["hgvs_c"]
            writer.writerow(row)
    paths["GLM_ADAR_EDIT_DIR"] = adar
    # The 05 alledit stage follows handoff in `all`; don't reuse historical alledit.
    paths["METAGENE_ALLEDIT_DIR"] = Path(a.alledit_dir).resolve()
    out.write_text(
        "# Generated by 05 handoff; Adar retains original source-ANN coordinates.\n"
        + "\n".join(
            f"export {key}={shlex.quote(str(value))}" for key, value in paths.items()
        )
        + "\n"
    )
    print(out)


if __name__ == "__main__":
    main()
