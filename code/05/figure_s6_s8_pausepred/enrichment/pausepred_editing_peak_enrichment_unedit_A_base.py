#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""Nucleotide-level PausePred enrichment with an A-base unedited background.

The observation unit is one transcript nucleotide position.  All edited
positions in the filtered PausePred universe are retained, matching the
historical all-edit analysis.  The unedited comparison set is restricted to
reference A bases in CDS regions.  PausePred peaks are defined at nucleotide
positions by Pause_score, and ``window_nt`` expands those peaks on the
transcript coordinate axis.  Thus this is an A-base-filtered unedited
background, not a codon-level analysis.
"""

import argparse
import csv
import importlib.util
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import fisher_exact

SCRIPT_DIR = Path(__file__).resolve().parent
BASE_PATH = SCRIPT_DIR / "pausepred_editing_peak_enrichment_new_transcript_merged.py"
spec = importlib.util.spec_from_file_location("pausepred_base", BASE_PATH)
if spec is None or spec.loader is None:
    raise RuntimeError(f"Cannot import base enrichment functions from {BASE_PATH}")
base = importlib.util.module_from_spec(spec)
spec.loader.exec_module(base)


def parse_args():
    parser = argparse.ArgumentParser(
        description=(
            "Nucleotide-level PausePred Fisher enrichment using reference "
            "A bases in CDS as the unedited background."
        )
    )
    parser.add_argument("--pausepred", required=True)
    parser.add_argument(
        "--editing-sites-used-in-universe",
        required=True,
        help="Canonical editing_sites_used_in_universe.tsv from the all-edit run.",
    )
    parser.add_argument(
        "--a-base-map",
        "--a-codon-map",
        dest="a_base_map",
        required=True,
        help="Compressed TSV generated by build_pausepred_a_base_map.py.",
    )
    parser.add_argument("--out", required=True)
    parser.add_argument("--min-reads", type=float, default=2)
    parser.add_argument("--min-coverage", type=float, default=20)
    parser.add_argument("--pause-cutoffs", default="5,10")
    parser.add_argument("--windows", default="0,2")
    parser.add_argument("--write-intermediate", action="store_true")
    # Compatibility with the shared wrapper.  The analysis itself always
    # keeps all edited sites and filters only the unedited background.
    parser.add_argument(
        "--background-mode", default="unedited_A_base", help=argparse.SUPPRESS
    )
    return parser.parse_args()


def read_editing_site_keys(path):
    table = pd.read_csv(
        path,
        sep="\t",
        dtype={"site_key": str},
        usecols=["site_key"],
        low_memory=False,
    )
    keys = table["site_key"].astype(str).str.strip()
    keys = keys[~keys.isin({"", "nan", "NA", "None"})]
    return set(keys)


def read_a_base_map(path):
    table = pd.read_csv(path, sep="\t", compression="infer", low_memory=False)
    required = {"transcript_id", "transcript_pos_1based", "reference_base"}
    missing = sorted(required - set(table.columns))
    if missing:
        raise RuntimeError(f"A-base map is missing columns {missing}: {path}")

    table["transcript_id"] = table["transcript_id"].astype(str).str.strip()
    table["transcript_pos_1based"] = pd.to_numeric(
        table["transcript_pos_1based"], errors="coerce"
    )
    table["reference_base"] = table["reference_base"].astype(str).str.upper()
    table = table[
        table["transcript_id"].ne("")
        & table["transcript_pos_1based"].notna()
        & table["reference_base"].eq("A")
    ].copy()
    table["transcript_pos_1based"] = table["transcript_pos_1based"].astype(int)
    return set(
        table["transcript_id"] + "_" + table["transcript_pos_1based"].astype(str)
    )


def write_optional_intermediates(prefix, pause, a_base_sites, unedited_a_keys):
    pause.to_csv(prefix + ".pausepred_universe.tsv", sep="\t", index=False)
    a_mask = pause["site_key"].isin(a_base_sites)
    pause.loc[a_mask].to_csv(prefix + ".A_base_sites.tsv", sep="\t", index=False)
    pause[pause["site_key"].isin(unedited_a_keys)].to_csv(
        prefix + ".unedited_A_base_sites.tsv", sep="\t", index=False
    )


def main():
    args = parse_args()
    pause_cutoffs = base.parse_num_list(args.pause_cutoffs, cast=float)
    window_list = base.parse_num_list(args.windows, cast=int)

    print(f"[INFO] Reading PausePred: {args.pausepred}")
    pause = base.read_pausepred(
        args.pausepred,
        min_reads=args.min_reads,
        min_coverage=args.min_coverage,
    )
    print(f"[INFO] PausePred universe after filters: {len(pause):,}")

    print(
        f"[INFO] Reading canonical editing keys: {args.editing_sites_used_in_universe}"
    )
    editing_keys = read_editing_site_keys(args.editing_sites_used_in_universe)
    universe_set = set(pause["site_key"])
    all_editing_in_universe = editing_keys & universe_set

    print(f"[INFO] Reading reference A-base map: {args.a_base_map}")
    mapped_a_keys = read_a_base_map(args.a_base_map)
    a_base_sites = mapped_a_keys & universe_set
    # Keep all edited positions, as in enrichment_alledit_cds.  Only the
    # unedited comparison set is restricted to reference A bases.
    editing_in_analysis = all_editing_in_universe
    unedited_a_keys = (universe_set - all_editing_in_universe) & a_base_sites

    print(
        f"[INFO] Canonical editing sites in original universe: {len(all_editing_in_universe):,}"
    )
    print(f"[INFO] Reference A bases in PausePred universe: {len(a_base_sites):,}")
    print(f"[INFO] Edited sites retained for analysis: {len(editing_in_analysis):,}")
    print(
        f"[INFO] Edited sites outside A-base universe: {len(all_editing_in_universe - a_base_sites):,}"
    )
    print(f"[INFO] Unedited A-base background sites: {len(unedited_a_keys):,}")

    original_unedited_total = len(universe_set - all_editing_in_universe)
    output_rows = []
    hit_records = []

    for cutoff in pause_cutoffs:
        peak = pause[pause["Pause_score"] >= cutoff].copy()
        for window_nt in window_list:
            target_keys = base.make_target_keys_from_peak(
                pause=pause,
                peak=peak,
                universe_set=universe_set,
                window_nt=window_nt,
            )
            editing_in_peak = len(editing_in_analysis & target_keys)
            editing_total = len(editing_in_analysis)
            editing_not_in_peak = editing_total - editing_in_peak
            nonediting_in_peak = len(unedited_a_keys & target_keys)
            nonediting_total = len(unedited_a_keys)
            nonediting_not_in_peak = nonediting_total - nonediting_in_peak

            fisher_table = [
                [editing_in_peak, editing_not_in_peak],
                [nonediting_in_peak, nonediting_not_in_peak],
            ]
            odds_ratio, p_value = fisher_exact(fisher_table, alternative="greater")

            output_rows.append(
                {
                    "Pause_score_cutoff": cutoff,
                    "window_nt": window_nt,
                    "min_reads_for_pause": args.min_reads,
                    "min_coverage_for_pause": args.min_coverage,
                    "total_sites_original_pausepred_universe": len(universe_set),
                    "total_sites_original_unedited": original_unedited_total,
                    "a_base_sites_in_pausepred_universe": len(a_base_sites),
                    "unedited_A_base_sites_removed": (
                        original_unedited_total - nonediting_total
                    ),
                    "comparison_sites": editing_total + nonediting_total,
                    "editing_sites_inside_A_base_in_original_universe": len(
                        all_editing_in_universe & a_base_sites
                    ),
                    "editing_sites_outside_A_base_in_original_universe": len(
                        all_editing_in_universe - a_base_sites
                    ),
                    "total_sites": editing_total + nonediting_total,
                    "total_sites_in_peak": editing_in_peak + nonediting_in_peak,
                    "total_sites_not_in_peak": (
                        editing_not_in_peak + nonediting_not_in_peak
                    ),
                    "editing_total_extracted_from_input": len(editing_keys),
                    "editing_total_used_in_original_universe": len(
                        all_editing_in_universe
                    ),
                    "editing_total_used_in_universe": editing_total,
                    "editing_in_peak": editing_in_peak,
                    "editing_not_in_peak": editing_not_in_peak,
                    "nonediting_total": nonediting_total,
                    "nonediting_in_peak": nonediting_in_peak,
                    "nonediting_not_in_peak": nonediting_not_in_peak,
                    "odds_ratio": odds_ratio,
                    "p_value": p_value,
                    "p_adj_BH": np.nan,
                    "multiple_testing_correction": "none",
                    "analysis_unit": "nucleotide_position",
                    "edited_background_filter": "all_valid_editing_sites",
                    "unedit_background_filter": "reference_CDS_base_is_A",
                }
            )

            if args.write_intermediate and window_nt == window_list[0]:
                hit_keys = editing_in_analysis & target_keys
                if hit_keys:
                    hit_records.append(
                        pause[pause["site_key"].isin(hit_keys)].assign(
                            Pause_score_cutoff=cutoff,
                            window_nt=window_nt,
                        )
                    )

    out_df = pd.DataFrame(output_rows)
    out_df.to_csv(args.out, sep="\t", index=False)
    print(f"[INFO] Main output written: {args.out}")

    prefix = str(args.out)
    if prefix.endswith(".tsv"):
        prefix = prefix[:-4]

    qc = pd.DataFrame(
        [
            {
                "pausepred_file": args.pausepred,
                "editing_sites_file": args.editing_sites_used_in_universe,
                "a_base_map": args.a_base_map,
                "pausepred_universe_sites": len(universe_set),
                "editing_sites_in_original_pausepred_universe": len(
                    all_editing_in_universe
                ),
                "editing_sites_inside_A_base_in_original_universe": len(
                    all_editing_in_universe & a_base_sites
                ),
                "editing_sites_outside_A_base_in_original_universe": len(
                    all_editing_in_universe - a_base_sites
                ),
                "original_unedited_sites": original_unedited_total,
                "pausepred_sites_in_A_base_universe": len(a_base_sites),
                "unedited_A_base_sites": len(unedited_a_keys),
                "unedited_sites_removed": original_unedited_total
                - len(unedited_a_keys),
                "comparison_sites": len(editing_in_analysis) + len(unedited_a_keys),
                "analysis_unit": "nucleotide_position",
                "edited_background_filter": "all_valid_editing_sites",
                "unedit_background_filter": "reference_CDS_base_is_A",
            }
        ]
    )
    qc.to_csv(prefix + ".unedit_A_base_filter_QC.tsv", sep="\t", index=False)

    if args.write_intermediate:
        write_optional_intermediates(
            prefix,
            pause,
            a_base_sites,
            unedited_a_keys,
        )
        if hit_records:
            pd.concat(hit_records, ignore_index=True).to_csv(
                prefix + ".editing_sites_in_peak.tsv", sep="\t", index=False
            )

    print(f"[INFO] QC output written: {prefix}.unedit_A_base_filter_QC.tsv")


if __name__ == "__main__":
    main()
